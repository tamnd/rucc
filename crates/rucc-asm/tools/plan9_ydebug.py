"""Write the yacc debug tables of 6a or 7a as Rust.

usage:
    python3 -I plan9_ydebug.py 6|7 DIR SYNTAX > SYNTAX/ydebugN.rs

DIR has the output of the yacc of the pin for the grammar of the assembler, made with
`yacc -D1 -d a.y`, as the mkfile of the assembler does: y.tab.c, y.tab.h and y.debug. Run that
command in /sys/src/cmd/6a or /sys/src/cmd/7a of a guest at the pin, or run a host build of
/sys/src/cmd/yacc.c of the pin. SYNTAX is
src/plan9/syntax. The tokens are the tokens of lex.rs and itabN.rs, because the lexer of rucc
returns no other token. The grammar of 7a has tokens that the lexer never returns.

The parser of rucc does not use these tables to parse. At a syntax error, it runs the parser of
yacc again on the tokens of the line, to find the state of yacc and the text that yacc prints
for that state.
"""
import os
import re
import sys


def arrays(text):
    out = {}
    for m in re.finditer(r"(?:short|long)\s+(yy\w+)\[\]\s*=\s*\{([^}]*)\}", text):
        out[m.group(1)] = [int(x) for x in m.group(2).replace("\n", " ").split(",") if x.strip()]
    return out


def strings(text, name):
    m = re.search(r"char\*\s+" + name + r"\[\]\s*=\s*\{(.*?)\n\};", text, re.S)
    out = []
    for line in m.group(1).split("\n"):
        line = line.strip()
        if not line:
            continue
        if line.startswith("0,"):
            out.append(None)
            continue
        s = re.match(r'"((?:[^"\\]|\\.)*)"', line).group(1)
        out.append(re.sub(r"\\(.)", lambda e: {"n": "\n", "t": "\t"}.get(e.group(1), e.group(1)), s))
    return out


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") + '"'


def table(name, values):
    lines = [f"static {name}: [i16; {len(values)}] = ["]
    for i in range(0, len(values), 16):
        lines.append("    " + ", ".join(str(v) for v in values[i:i + 16]) + ",")
    lines.append("];")
    return "\n".join(lines)


def main():
    machine, d, syntax = sys.argv[1], sys.argv[2], sys.argv[3]
    known = set()
    for f in ["lex.rs", f"itab{machine}.rs"]:
        known |= set(re.findall(r"const (L\w+): i32", open(os.path.join(syntax, f)).read()))
    tab = open(os.path.join(d, "y.tab.c")).read()
    dbg = open(os.path.join(d, "y.debug")).read()
    hdr = open(os.path.join(d, "y.tab.h")).read()
    a = arrays(tab)
    last = int(re.search(r"#define\s+YYLAST\s+(\d+)", tab).group(1))
    private = int(re.search(r"#define\s+YYPRIVATE\s+(\d+)", tab).group(1))
    tokens = {m.group(1): int(m.group(2)) for m in re.finditer(r"#define\s+(\w+)\s+(\d+)", hdr)}
    names = strings(dbg, "yytoknames")
    states = strings(dbg, "yystates")
    tok1, tok2, tok3 = a["yytok1"], a["yytok2"], a["yytok3"]

    def code(c):
        # yylex1 of yaccpar.
        if c <= 0:
            return tok1[0]
        if c < len(tok1):
            v = tok1[c]
        elif private <= c < private + len(tok2):
            v = tok2[c - private]
        else:
            v = 0
            for i in range(0, len(tok3) - 1, 2):
                if tok3[i] == c:
                    v = tok3[i + 1]
                    break
        return v if v else tok2[1]

    print(f"//! The tables of Plan 9 yacc for the grammar `{machine}a/a.y` at the pin, for the debug text of a")
    print("//! syntax error.")
    print("//!")
    print(f"//! This file is generated by `tools/plan9_ydebug.py` from the output of `yacc -D1 -d a.y`. The")
    print("//! yacc is the yacc of the pin.")
    print()
    print("#![allow(clippy::unreadable_literal)]")
    print()
    print(f"use super::itab{machine}::*;")
    print("use super::lex::{LCONST, LFCONST, LLAB, LNAME, LSCONST, LVAR};")
    print("use super::yacc::Tables;")
    print()
    print("#[rustfmt::skip]")
    print("pub(super) static TABLES: Tables = Tables {")
    for k in ["exca", "act", "pact", "pgo", "r1", "r2", "chk", "def"]:
        print(f"    {k}: &{k.upper()},")
    print(f"    last: {last},")
    print("    code,")
    print("    names: &NAMES,")
    print("    states: &STATES,")
    print("};")
    print()
    print("/// `yylex1`: the code of yacc for the token `t` of the lexer.")
    print("fn code(t: i32) -> i32 {")
    print("    match t {")
    for n, v in sorted(tokens.items(), key=lambda x: x[1]):
        if n not in known:
            continue
        print(f"        {n} => {code(v)},")
    print(f"        i32::MIN..=0 => {tok1[0]},")
    print(f"        1..={len(tok1) - 1} => i32::from(TOK1[usize::try_from(t).unwrap_or(0)]),")
    print(f"        _ => {tok2[1]},")
    print("    }")
    print("}")
    print()
    for k in ["exca", "act", "pact", "pgo", "r1", "r2", "chk", "def", "tok1"]:
        print("#[rustfmt::skip]")
        print(table(k.upper(), a["yy" + k]))
        print()
    print(f"static NAMES: [&str; {len(names)}] = [")
    for s in names:
        print(f"    {rust_str(s or '')},")
    print("];")
    print()
    print(f"static STATES: [&str; {len(states)}] = [")
    for s in states:
        print(f"    {rust_str(s or '')},")
    print("];")


if __name__ == "__main__":
    main()
